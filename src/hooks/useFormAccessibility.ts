import { useId } from 'react'

export interface FormFieldIds {
  /** `id` for the `<input>` / `<select>` / `<textarea>`. */
  inputId: string
  /** `htmlFor` for the `<label>` — identical to `inputId`. */
  labelId: string
  /** `id` for the inline error message — pass to `aria-describedby` when an error is present. */
  errorId: string
  /** `id` for the hint / helper text — pass to `aria-describedby` when shown. */
  hintId: string
}

/**
 * Generates stable, unique IDs for every element that makes up an accessible
 * form field: the control itself, its label, an optional error message, and an
 * optional hint.
 *
 * Usage:
 *
 *   const ids = useFormAccessibility()
 *
 *   <label htmlFor={ids.labelId}>Email</label>
 *   <input
 *     id={ids.inputId}
 *     aria-describedby={error ? ids.errorId : hint ? ids.hintId : undefined}
 *     aria-invalid={error ? 'true' : 'false'}
 *   />
 *   {hint && <p id={ids.hintId}>{hint}</p>}
 *   {error && <p id={ids.errorId} role="alert">{error}</p>}
 *
 * IDs are generated by React's `useId` so they are stable across renders,
 * unique per component instance, and safe for server-side rendering.
 */
export function useFormAccessibility(): FormFieldIds {
  const base = useId()
  return {
    inputId: `${base}-input`,
    labelId: `${base}-input`,
    errorId: `${base}-error`,
    hintId: `${base}-hint`,
  }
}
